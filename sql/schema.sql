INSERT INTO storage.buckets (id, name, public) 
VALUES 
  ('member-avatars', 'member-avatars', true),
  ('legal-docs', 'legal-docs', true)
ON CONFLICT (id) DO NOTHING;

-- Configura políticas de upload e download
DO $$
BEGIN
    -- Avatars
    DROP POLICY IF EXISTS "Avatars Publicos" ON storage.objects;
    CREATE POLICY "Avatars Publicos" ON storage.objects FOR SELECT USING ( bucket_id = 'member-avatars' );
    
    DROP POLICY IF EXISTS "Avatars Upload" ON storage.objects;
    CREATE POLICY "Avatars Upload" ON storage.objects FOR INSERT TO authenticated WITH CHECK ( bucket_id = 'member-avatars' );

    -- Docs
    DROP POLICY IF EXISTS "Docs Publicos" ON storage.objects;
    CREATE POLICY "Docs Publicos" ON storage.objects FOR SELECT USING ( bucket_id = 'legal-docs' );

    DROP POLICY IF EXISTS "Docs Upload" ON storage.objects;
    CREATE POLICY "Docs Upload" ON storage.objects FOR INSERT TO authenticated WITH CHECK ( bucket_id = 'legal-docs' );
END $$;
